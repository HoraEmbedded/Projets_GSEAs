def plot_latent_space(model, dataloader):
    """Génère le Scatter Plot de l'espace latent."""
    model.eval()
    z_coords, labels = [], []

    with torch.no_grad():
        for data, target in dataloader:
            data = data.to(DEVICE)
            mu, _ = model.encode(data.view(data.size(0), -1))
            z_coords.append(mu.cpu().numpy())
            labels.append(target.numpy())

    z_coords = np.concatenate(z_coords, axis=0)
    labels = np.concatenate(labels, axis=0)

    plt.figure(figsize=(10, 8))
    scatter = plt.scatter(z_coords[:, 0], z_coords[:, 1], c=labels, cmap='tab10', alpha=0.7, s=5)
    plt.colorbar(scatter, ticks=range(10))
    plt.title("Visualisation 2D de l'Espace Latent du VAE")
    plt.xlabel("Dimension Latente z1")
    plt.ylabel("Dimension Latente z2")
    plt.grid(True, alpha=0.3)
    plt.show()

def plot_generated_manifold(model, grid_size=15, range_val=2.0):
    """Génère la grille de transition fluide (Manifold) en scannant l'espace latent."""
    model.eval()
    figure = np.zeros((28 * grid_size, 28 * grid_size))

    # Création d'une grille de coordonnées 2D (de -range_val à +range_val)
    grid_x = np.linspace(-range_val, range_val, grid_size)
    grid_y = np.linspace(range_val, -range_val, grid_size)

    with torch.no_grad():
        for i, yi in enumerate(grid_y):
            for j, xi in enumerate(grid_x):
                z_sample = torch.tensor([[xi, yi]], dtype=torch.float32).to(DEVICE)
                x_decoded = model.decode(z_sample).cpu().view(28, 28).numpy()
                figure[i * 28: (i + 1) * 28, j * 28: (j + 1) * 28] = x_decoded

    plt.figure(figsize=(10, 10))
    plt.imshow(figure, cmap='gray')
    plt.title("Images Générées en scannant l'Espace Latent")
    plt.axis('off')
    plt.show()

# Affichage des graphiques
plot_latent_space(vae_model, test_loader)
